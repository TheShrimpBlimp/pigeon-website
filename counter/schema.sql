CREATE TABLE IF NOT EXISTS counter (id INTEGER PRIMARY KEY CHECK (id = 1), total INTEGER NOT NULL DEFAULT 0);
INSERT OR IGNORE INTO counter (id, total) VALUES (1, 0);
CREATE TABLE IF NOT EXISTS trials (id TEXT PRIMARY KEY, day TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS external_install_counts (source TEXT PRIMARY KEY, total INTEGER NOT NULL CHECK(total >= 0), checked_at INTEGER NOT NULL);
